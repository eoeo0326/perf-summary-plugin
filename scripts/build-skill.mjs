import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const check = process.argv.includes('--check');
const result = await build({
  absWorkingDir: root, entryPoints: ['src/cli/entry.ts'], bundle: true,
  platform: 'node', format: 'esm', target: 'node22', minify: true,
  legalComments: 'inline', write: false, charset: 'utf8',
  define: { __PERF_SUMMARY_VERSION__: JSON.stringify(pkg.version) },
  banner: { js: '#!/usr/bin/env node\n// Generated by npm run build:skill. Edit src/cli/, not this bundle.' },
});
const notices = [];
for (const [name, license] of [['luxon', 'LICENSE.md'], ['zod', 'LICENSE']]) {
  const dependency = JSON.parse(await readFile(path.join(root, 'node_modules', name, 'package.json'), 'utf8'));
  notices.push(name + '@' + dependency.version + '\n\n' +
    await readFile(path.join(root, 'node_modules', name, license), 'utf8'));
}
const files = new Map([
  ['skills/perf-summary/scripts/perf-summary.mjs', result.outputFiles[0].text],
  ['skills/perf-summary/THIRD_PARTY_NOTICES.txt', notices.join('\n\n---\n\n')],
  ['skills/perf-summary/LICENSE', await readFile(path.join(root, 'LICENSE'), 'utf8')],
  ['resources/report-guidelines.md', await readFile(path.join(root, 'skills/perf-summary/references/report-guidelines.md'), 'utf8')],
]);
for (const [name, content] of files) {
  const target = path.join(root, name);
  if (check) {
    assert.equal(await readFile(target, 'utf8'), content, name + ': stale artifact; run npm run build:skill');
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, content);
  }
}
console.log(check ? 'Skill bundle, licenses and shared guidelines are current.' : 'Standalone skill bundle and shared resources generated.');
